'''
3. 运算符
Python中的运算符主要分为以下几类：

算术运算符
运算符	描述	例子	结果
+	加法	3 + 5	8
-	减法	10 - 4	6
*	乘法	2 * 6	12
/	除法	10 / 2	5.0
//	整除	10 // 3	3
%	取余	10 % 3	1
**	幂运算	2 ** 3	8
'''

a = 10
b = 3

print("a =", a)
print("b =", b)

print("a + b =", a + b)  # 加法   
print("a - b =", a - b)  # 减法    
print("a * b =", a * b)  # 乘法        
print("a / b =", a / b)  # 除法    
print("a // b =", a // b)  # 整除   
print("a % b =", a % b)  # 取余    
print("a ** b =", a ** b)  # 幂运算  
