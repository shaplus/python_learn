'''
1. 变量
变量是用来存储数据的容器,在Python中定义变量非常简单:

语法：变量名 = 值
注意事项：

变量名只能包含字母、数字和下划线
变量名不能以数字开头
变量名区分大小写(name 和 Name 是不同的变量)
变量名最好有意义，便于理解
'''
# 定义一个整数变量
age = 18
print(age)
print(type(age))

# 定义一个字符串变量
name = "Alice"
print(name)
print(type(name))
# 定义一个浮点数变量
height = 1.65
print(height)
print(type(height))