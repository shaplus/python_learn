'''
比较运算符
运算符	描述	例子	结果
==	等于	5 == 5	True
!=	不等于	5 != 3	True
>	大于	5 > 3	True
<	小于	5 < 3	False
>=	大于等于	5 >= 5	True
<=	小于等于	5 <= 3	False
'''

x = 5
y = 3
print('x=', x)
print('y=', y)
print('x == y:', x == y)  # False
print('x != y:', x != y)  # True
print('x > y:', x > y)  # True  
print('x < y:', x < y)  # False
print('x >= y:', x >= y)  # True
print('x <= y:', x <= y)  # True 
